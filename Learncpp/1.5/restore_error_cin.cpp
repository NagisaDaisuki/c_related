#include <iostream>
#include <limits>
#include <string>

/**
*  std::cin >> 的底层运作机制，完全可以提炼为这两大核心要素：

前导操作（“智能过滤器”）： 这是 cin >>
真正开始干活前的“清道夫”动作。它会自动且无情地丢弃当前位置所有的前导空白符（空格、Tab、换行
\n），直到摸到第一个实质性字符为止。这正是为什么 cin >> x >> y;
时，无论你是用空格隔开 4 5，还是按回车分两行输入，它都能完美提取的原因。

类型校验（“错误判定的命门”）：
这是决定本次提取能否成功的生死关卡。当它跳过空白符开始真正“吃”字符时，会死死盯着你提供的“变量类型”。如果缓冲区里的字符和变量类型不匹配（比如你要
int，它遇到了字母 A；或者甚至你要
double，它遇到了多个小数点），提取就会立刻崩盘。
*/

/*
 *  “类型不匹配”带来的毁灭性连锁反应

在 C++ 中，这种类型校验失败不仅是“提取不到数据”那么简单，它会直接改变 std::cin
这个对象本身的状态：

拉响警报（设置 failbit）： cin
内部有一个状态位，一旦发现类型不匹配，它就会把一个叫做
failbit（失败标志）的开关打开。

彻底罢工： 正如上文提到的“步骤 1”，一旦 cin
处于这种错误状态，它就像是进入了系统死锁。在这之后，你代码里写的哪怕后面还有 100
个 cin >>，它都会瞬间略过，绝对不会再停下来等你输入。

罪魁祸首留在现场： 那个导致出错的字母（比如 A）依然死死卡在缓冲区的前排。

所以，检验类型是否匹配，不仅是判断对错的要素，更是掌控整个程序后续输入能否正常进行的总开关。理解了这一点，你也就彻底懂了
C++ 输入流的脾气。
 * */

// 修复死锁的 std::cin 必须严格按照先重置状态，再清空物理缓冲区的顺序进行。

int main() {
  int var{};
  std::cin >> var; // 假设这里接收的是一个字符串字面量 "Hello"
  // 触发"类型不匹配", 设置failbit状态位为打开，随后的cin都会罢工不再执行
  std::string str[20]{};
  // 如果第一个cin失败后面的就都会处于死循环跳过状态
  std::cin >> str[0];
  std::cin >> str[1];

  // 步骤1：解除死锁(重置内部状态位)
  std::cin.clear();

  // 步骤2：物理清场（丢弃缓冲区里的所有非法残留物）
  std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');

  std::cout << var << '\n';
  return 0;
}
